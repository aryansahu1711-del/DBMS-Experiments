CREATE DATABASE Experiment7DB;

USE Experiment7DB;

CREATE TABLE AREAS (
    AREAID INT PRIMARY KEY,
    LOCATION VARCHAR(50)
);

CREATE TABLE DEPT (
    DEPTNO INT PRIMARY KEY,
    DNAME VARCHAR(50),
    AREAID INT
);

CREATE TABLE EMP (
    EMPNO INT PRIMARY KEY,
    ENAME VARCHAR(50),
    JOB VARCHAR(30),
    MGR INT,
    SAL DECIMAL(10,2),
    DEPTNO INT
);

CREATE TABLE SALGRADE (
    GRADE INT PRIMARY KEY,
    LOSAL DECIMAL(10,2),
    HISAL DECIMAL(10,2)
);

