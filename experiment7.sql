SELECT
    E.EMPNO,
    E.ENAME,
    D.DNAME,
    A.LOCATION
FROM EMP E
JOIN DEPT D ON E.DEPTNO = D.DEPTNO
JOIN AREAS A ON D.AREAID = A.AREAID;

SELECT
    E.EMPNO,
    E.ENAME,
    E.SAL,
    S.GRADE
FROM EMP E
JOIN SALGRADE S
ON E.SAL BETWEEN S.LOSAL AND S.HISAL;

SELECT
    E.ENAME AS EmployeeName,
    M.ENAME AS ManagerName
FROM EMP E
LEFT JOIN EMP M
ON E.MGR = M.EMPNO;

SELECT
    E.ENAME,
    D.DNAME
FROM EMP E
CROSS JOIN DEPT D;

SELECT
    E.EMPNO,
    E.ENAME,
    D.DNAME
FROM EMP E
INNER JOIN DEPT D
ON E.DEPTNO = D.DEPTNO;

